package com.narad.search.lib.query.model

import com.narad.search.lib.query.TestModel
import org.junit.Assert.*
import org.junit.Before
import org.junit.BeforeClass
import org.junit.Test

/**
 * JVM golden-reference test for the EmbeddingGemma 2 SentencePiece tokenizer.
 *
 * Encodes two fixed samples (English + Hindi Devanagari) using the DJL
 * HuggingFaceTokenizer (host-native, macOS arm64) and asserts byte-for-byte
 * equality against hardcoded expected token-ID arrays.
 *
 * These constants serve as the golden reference for the on-device parity test
 * [com.narad.search.lib.query.model.TokenizerParityTest], which encodes the
 * same sentences with [DjlTokenizer] on the emulator and asserts the same IDs.
 *
 * EmbeddingGemma 2 special tokens (Gemma 2 vocabulary):
 *  - BOS: `<bos>` = 2
 *  - EOS: `<eos>` = 1
 * The tokenizer adds BOS automatically; EOS appears at end of sequence.
 * (Previously Granite used BOS=179934, EOS=179938 - those IDs are obsolete.)
 */
class TokenizerGoldenReferenceTest {

    companion object {
        // Fixed sentences that exercise BPE merges in English and Hindi Devanagari.
        // Same strings as before - only token IDs changed for EG2.
        const val SENTENCE_EN = "The tenant must pay a penalty for late rent."
        const val SENTENCE_HI = "किरायेदार को देर से किराया देने पर जुर्माना देना होगा।"

        // -------------------------------------------------------------------------
        // Hardcoded golden arrays - generated by running the Python tokenizer
        // (tokenizers 0.23.2, EmbeddingGemma 2 tokenizer.json, 2026-10-08).
        // -------------------------------------------------------------------------
        // EN: 12 tokens (BOS + 10 subwords + EOS)
        val EXPECTED_EN_IDS: LongArray = longArrayOf(
            2, 818, 28715, 1921, 2350, 496, 20256, 573, 5226, 7801, 236761, 1
        )

        // HI: 16 tokens (BOS + 14 Devanagari subwords + EOS)
        val EXPECTED_HI_IDS: LongArray = longArrayOf(
            2, 4286, 2208, 6251, 10782, 1198, 40525, 1248, 154635, 15327, 1539, 198151, 25227, 7582, 236890, 1
        )

        /** BOS token id for EmbeddingGemma 2 (Gemma 2 vocab). */
        const val BOS_TOKEN_ID = 2L

        /** EOS token id for EmbeddingGemma 2 (Gemma 2 vocab). */
        const val EOS_TOKEN_ID = 1L

        private lateinit var tokenizer: HuggingFaceTokenizer

        @JvmStatic
        @BeforeClass
        fun setUpClass() {
            // Guard: do not access TestModel properties when model is absent.
            // The @Before skipIfModelMissing handles the per-test JUnit Assume skip.
            if (!TestModel.shouldRunModelTests()) return
            tokenizer = HuggingFaceTokenizer(TestModel.tokenizerJsonPath)
        }
    }

    @Before
    fun skipIfModelMissing() {
        TestModel.skipIfMissing()
    }

    @Test
    fun `golden EN token IDs match hardcoded reference`() {
        val enc = tokenizer.encode(SENTENCE_EN)
        println("EN inputIds (${enc.inputIds.size} tokens) = ${enc.inputIds.toList()}")

        assertEquals(
            "EN: token count mismatch",
            EXPECTED_EN_IDS.size,
            enc.inputIds.size
        )
        assertArrayEquals(
            "EN: token IDs do not match golden reference",
            EXPECTED_EN_IDS,
            enc.inputIds
        )
    }

    @Test
    fun `golden HI token IDs match hardcoded reference`() {
        val enc = tokenizer.encode(SENTENCE_HI)
        println("HI inputIds (${enc.inputIds.size} tokens) = ${enc.inputIds.toList()}")

        assertEquals(
            "HI: token count mismatch",
            EXPECTED_HI_IDS.size,
            enc.inputIds.size
        )
        assertArrayEquals(
            "HI: token IDs do not match golden reference",
            EXPECTED_HI_IDS,
            enc.inputIds
        )
    }

    @Test
    fun `EN prefix is BOS`() {
        val enc = tokenizer.encode(SENTENCE_EN)
        assertEquals(
            "EN: first token must be BOS (<bos>=2), got ${enc.inputIds.first()}",
            BOS_TOKEN_ID,
            enc.inputIds.first()
        )
    }

    @Test
    fun `EN suffix is EOS`() {
        val enc = tokenizer.encode(SENTENCE_EN)
        assertEquals(
            "EN: last token must be EOS (<eos>=1), got ${enc.inputIds.last()}",
            EOS_TOKEN_ID,
            enc.inputIds.last()
        )
    }

    @Test
    fun `HI prefix is BOS`() {
        val enc = tokenizer.encode(SENTENCE_HI)
        assertEquals(
            "HI: first token must be BOS (<bos>=2), got ${enc.inputIds.first()}",
            BOS_TOKEN_ID,
            enc.inputIds.first()
        )
    }

    @Test
    fun `HI suffix is EOS`() {
        val enc = tokenizer.encode(SENTENCE_HI)
        assertEquals(
            "HI: last token must be EOS (<eos>=1), got ${enc.inputIds.last()}",
            EOS_TOKEN_ID,
            enc.inputIds.last()
        )
    }
}
